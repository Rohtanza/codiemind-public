#!/usr/bin/env python3
"""Stage 6 — audit the run records before any analysis. Writes out/run_audit.md; exit 1 on any failure.

What each check tests (and the failure it would catch):
  C1 trial set   each full run's trial_keys equal EXACTLY the designed set (cases × arms × sizes × reps,
                 135 × 9 × 3 = 3,645); each variance file equals its 5 cases × 10 reps × arm C × size 10.
                 Catches missing, duplicated or extra trials (e.g. a resume that re-ran or skipped).
  C2 provenance  stub false; model_label = file's model; served llm_call.model = requested id;
                 cases_sha256 = sha256 of the frozen stage5 out/cases.jsonl.
  C3 decoding    temperature 0, max_tokens 1024, seed 12345 on every trial.
  C4 instrument  every verifier_id/verifier_sha256 equals the registry entry used for analysis
                 (the instrument did not change under the run).
  C5 access      arm A target_in_prompt always false; arm B always true (static file carries the target).
  C6 integrity   response_sha256 = sha256(response); outcome in the five-value contract.
  C7 rescore     a seeded stratified sample of trials re-scored now with the registered verifiers gives
                 the recorded outcome (verifier purity; nothing edited a record after scoring).
Usage: python3 harness/verify_runs.py [--rescore N]      (default N = 60 per model)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import random
import sys
from collections import Counter

STAGE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(STAGE))
import run_benchmark as rb  # noqa: E402  (also puts the verifier dir on sys.path)
from registry import active, load  # noqa: E402
from runtime import score_response  # noqa: E402

MODELS = ("gpt-4o-mini-2024-07-18", "qwen.qwen3-coder-30b-a3b-instruct", "deepseek.v3.2")
VAR_CASES = ("R58_4-plain", "R10_35-plain", "R15_14-plain", "R14_3-plain", "R18_27-plain")
OUTCOMES = {"SATISFIED", "VIOLATED", "NOT_APPLICABLE", "NO_CODE", "MALFORMED"}
DECODING = {"temperature": 0.0, "max_tokens": 1024, "seed": 12345}


def sha(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def read(p: pathlib.Path) -> list[dict]:
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rescore", type=int, default=60)
    a = ap.parse_args()
    cases = [json.loads(x) for x in rb.CASES.read_text(encoding="utf-8").splitlines() if x.strip()]
    cases_sha = hashlib.sha256(rb.CASES.read_bytes()).hexdigest()
    reg = load()
    L = ["# Stage 6 — run-record audit", "",
         "Generated by `harness/verify_runs.py`. What each check tests is stated in the script docstring.", "",
         "| file | trials | C1 trial set | C2 provenance | C3 decoding | C4 instrument | C5 access | C6 integrity | C7 rescore |",
         "|---|---:|---|---|---|---|---|---|---|"]
    fails = []
    for m in MODELS:
        for kind in ("full", "variance"):
            p = STAGE / "runs" / (f"{m}.jsonl" if kind == "full" else f"variance_{m}.jsonl")
            rs = read(p)
            if kind == "full":
                want = {rb.trial_key(m, c, arm, n, rep) for c, arm, n, rep in rb.trials(cases, rb.ARMS, rb.SIZES, rb.REPS)}
            else:
                vc = [c for c in cases if c["case_id"] in VAR_CASES]
                want = {rb.trial_key(m, c, arm, n, rep) for c, arm, n, rep in rb.trials(vc, ["C"], [10], 10)}
            keys = [r["trial_key"] for r in rs]
            dup = len(keys) - len(set(keys))
            c1 = dup == 0 and set(keys) == want
            c1s = "ok" if c1 else f"FAIL dup={dup} missing={len(want - set(keys))} extra={len(set(keys) - want)}"
            bad2 = [r["trial_key"] for r in rs if r.get("stub") or r["model_label"] != m
                    or (r.get("llm_call") or {}).get("model") != m or r["cases_sha256"] != cases_sha]
            bad3 = [r["trial_key"] for r in rs if any((r.get("llm_call") or {}).get(k) != v for k, v in DECODING.items())]
            bad4 = []
            for r in rs:
                e = active(r["rule_id"], "ts" if r["verifier_id"].split(":")[1] == "ts" else "py", reg)
                if e is None or e["verifier_id"] != r["verifier_id"] or e["sha256"] != r["verifier_sha256"]:
                    bad4.append(r["trial_key"])
            bad5 = [r["trial_key"] for r in rs if (r["arm"] == "A" and r["target_in_prompt"]) or
                    (r["arm"] == "B" and not r["target_in_prompt"])]
            bad6 = [r["trial_key"] for r in rs if sha(r["response"]) != r["response_sha256"] or r["outcome"] not in OUTCOMES]
            # C7: stratified by outcome, seeded; full runs only (variance trials are the same instrument).
            c7s = "—"
            if kind == "full" and a.rescore:
                rng = random.Random(20261020)
                by = {}
                for r in rs:
                    by.setdefault(r["outcome"], []).append(r)
                sample = []
                for o in sorted(by):
                    sample += rng.sample(by[o], min(len(by[o]), max(1, a.rescore // len(by))))
                mism = []
                for r in sample:
                    e = active(r["rule_id"], r["verifier_id"].split(":")[1], reg)
                    got = score_response(r["response"], e).outcome
                    if got != r["outcome"]:
                        mism.append((r["trial_key"], r["outcome"], got))
                c7s = "ok" if not mism else f"FAIL {len(mism)}"
                c7s += f" ({len(sample)} re-scored)"
                if mism:
                    fails.append(f"{p.name} C7 {mism[:5]}")
            cells = [c1s] + ["ok" if not b else f"FAIL {len(b)}" for b in (bad2, bad3, bad4, bad5, bad6)] + [c7s]
            for name, b in zip(("C2", "C3", "C4", "C5", "C6"), (bad2, bad3, bad4, bad5, bad6)):
                if b:
                    fails.append(f"{p.name} {name}: {b[:3]}")
            if not c1:
                fails.append(f"{p.name} C1: {c1s}")
            L.append(f"| `{p.name}` | {len(rs)} | " + " | ".join(cells) + " |")
            if kind == "full":
                fr = Counter((r.get("llm_call") or {}).get("finish_reason") for r in rs)
                L.append(f"| ↳ finish_reason | | " + ", ".join(f"{k}: {v}" for k, v in fr.most_common()) + " | | | | | | |")
    L += ["", f"cases.jsonl sha256 `{cases_sha}`; registry version {reg.get('registry_version')}.",
          "", f"**{len(fails)} failed checks.**"] + [f"- {f}" for f in fails]
    (STAGE / "out").mkdir(exist_ok=True)
    (STAGE / "out" / "run_audit.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
