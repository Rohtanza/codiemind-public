#!/usr/bin/env python3
"""Stage 6 — diagnostics reported beside the pre-registered results. Writes out/diagnostics.md.

None of these is a pre-registered hypothesis test; none changes a trial, a verdict or r.
  D1 truncation   per model × arm × store: finish_reason=length, MALFORMED, NO_CODE, and the share of
                  trials that are scored at all (S, V or NA); MALFORMED split by finish_reason; the
                  completion length of scored vs unscored trials. max_tokens = 1024 was pre-registered
                  and is not changed; truncated trials are neither dropped nor repaired.
  D2 variance     the pre-registered decoding-variance diagnostic (5 cases × 10 repetitions, arm C,
                  store 10): distinct responses and distinct verdicts per case. Reported only; r = 3 stands.
  D3 retrieval    arm C retrieval rate and compliance-given-retrieval by distance and store size, to
                  read H1: does adherence fall with distance because the target stops being retrieved,
                  or because a retrieved target is followed less?
Usage: python3 harness/diagnostics.py
"""
from __future__ import annotations

import json
import pathlib
import statistics
from collections import Counter, defaultdict

STAGE = pathlib.Path(__file__).resolve().parent
MODELS = ("gpt-4o-mini-2024-07-18", "qwen.qwen3-coder-30b-a3b-instruct", "deepseek.v3.2")
SCORED = ("SATISFIED", "VIOLATED", "NOT_APPLICABLE")


def read(p):
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()]


def pct(a, b):
    return "—" if not b else f"{100 * a / b:.1f}%"


def adh(rs):
    s = sum(r["outcome"] == "SATISFIED" for r in rs)
    v = sum(r["outcome"] == "VIOLATED" for r in rs)
    return pct(s, s + v) + f" ({s + v})"


def fr(r):
    return (r.get("llm_call") or {}).get("finish_reason")


def main() -> int:
    runs = {m: read(STAGE / "runs" / f"{m}.jsonl") for m in MODELS}
    L = ["# Stage 6 — diagnostics (descriptive; not pre-registered tests)", "",
         "Generated by `harness/diagnostics.py` from `runs/*.jsonl`. max_tokens = 1024 was pre-registered, and "
         "; no trial is dropped, repaired or re-run.", "",
         "## D1 Truncation and unscored trials", "",
         "Scored = outcome SATISFIED, VIOLATED or NOT_APPLICABLE. MALFORMED = extracted code failed the "
         "compile gate (a response cut off mid-file usually fails it). Adherence counts only S and V.", "",
         "| model | arm | store | trials | finish=length | MALFORMED | NO_CODE | scored | adherence (S+V n) |",
         "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for m, rs in runs.items():
        for arm in ("A", "B", "C"):
            for n in ([None] if arm == "A" else [10, 30, 60, 120]):
                sub = [r for r in rs if r["arm"] == arm and r["store_size"] == n]
                c = Counter(r["outcome"] for r in sub)
                L.append(f"| {m} | {arm} | {n or '—'} | {len(sub)} | {pct(sum(fr(r) == 'length' for r in sub), len(sub))} | "
                         f"{pct(c['MALFORMED'], len(sub))} | {pct(c['NO_CODE'], len(sub))} | "
                         f"{pct(sum(c[o] for o in SCORED), len(sub))} | {adh(sub)} |")
    L += ["", "Per model, all arms:", "",
          "| model | trials | finish=length | MALFORMED | MALFORMED with finish=length | MALFORMED with finish=stop | NO_CODE | scored | median completion tokens, scored / unscored |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for m, rs in runs.items():
        c = Counter(r["outcome"] for r in rs)
        mal = [r for r in rs if r["outcome"] == "MALFORMED"]
        sc = [r for r in rs if r["outcome"] in SCORED]
        un = [r for r in rs if r["outcome"] not in SCORED]
        tok = lambda xs: statistics.median([(r.get("llm_call") or {}).get("completion_tokens") or 0 for r in xs]) if xs else 0
        L.append(f"| {m} | {len(rs)} | {pct(sum(fr(r) == 'length' for r in rs), len(rs))} | {pct(len(mal), len(rs))} | "
                 f"{sum(fr(r) == 'length' for r in mal)} | {sum(fr(r) == 'stop' for r in mal)} | {pct(c['NO_CODE'], len(rs))} | "
                 f"{pct(len(sc), len(rs))} ({len(sc)}) | {tok(sc):.0f} / {tok(un):.0f} |")

    L += ["", "## D2 Decoding-variance diagnostic (pre-registered; reported only, r = 3 unchanged)", "",
          "5 cases × 10 repetitions, arm C, store 10, temperature 0, seed 12345.", "",
          "| model | case | distinct responses / 10 | verdicts over 10 |", "|---|---|---:|---|"]
    for m in MODELS:
        rs = read(STAGE / "runs" / f"variance_{m}.jsonl")
        by = defaultdict(list)
        for r in rs:
            by[r["case_id"]].append(r)
        stable = 0
        for cid in sorted(by):
            xs = by[cid]
            vc = Counter(r["outcome"] for r in xs)
            stable += len(vc) == 1
            L.append(f"| {m} | {cid} | {len({r['response_sha256'] for r in xs})} | "
                     + ", ".join(f"{k} {v}" for k, v in vc.most_common()) + " |")
        L.append(f"| {m} | **cases with one verdict across all 10** | | **{stable} / {len(by)}** |")

    L += ["", "## D3 Arm C: retrieval and compliance by distance (reading H1)", "",
          "Retrieval = the target text is in the assembled prompt. Retrieval depends only on the shared "
          "embedding model and the scorer, so it is the same for every chat model.", "",
          "| model | distance | trials | retrieval | adherence, all (S+V n) | adherence, target retrieved | adherence, not retrieved |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for m, rs in runs.items():
        for d in (1, 5, 20):
            sub = [r for r in rs if r["arm"] == "C" and r["distance"] == d]
            L.append(f"| {m} | {d} | {len(sub)} | {pct(sum(r['target_in_prompt'] for r in sub), len(sub))} | {adh(sub)} | "
                     f"{adh([r for r in sub if r['target_in_prompt']])} | {adh([r for r in sub if not r['target_in_prompt']])} |")
    L += ["", "| store | distance | retrieval (gpt-4o-mini run) |", "|---:|---:|---:|"]
    rs = runs[MODELS[0]]
    for n in (10, 30, 60, 120):
        for d in (1, 5, 20):
            sub = [r for r in rs if r["arm"] == "C" and r["store_size"] == n and r["distance"] == d]
            L.append(f"| {n} | {d} | {pct(sum(r['target_in_prompt'] for r in sub), len(sub))} |")
    same = all([r["target_in_prompt"] for r in sorted((x for x in runs[m] if x["arm"] == "C"), key=lambda x: x["trial_key"].split("|", 1)[1])]
               == [r["target_in_prompt"] for r in sorted((x for x in runs[MODELS[0]] if x["arm"] == "C"), key=lambda x: x["trial_key"].split("|", 1)[1])]
               for m in MODELS)
    L += ["", f"Arm C retrieval flags identical trial-by-trial across the three models: **{same}**."]
    (STAGE / "out" / "diagnostics.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
